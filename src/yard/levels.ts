export function levelById(id: string): Level {
  return LEVELS.find((level) => level.id === id) || LEVELS[0]
}

export type Paint = { x: number; z: number; color: string }

export function inCanvas(level: Level, x: number, z: number): boolean {
  return x >= 0 && x < level.cols && z >= 0 && z < level.rows
}

/** Subject squares first, then the background, so a skip still shows the picture. */
export function cheatPaints(level: Level, percent: number): Paint[] {
  const counts = new Map<string, number>()
  for (const row of level.cells) {
    for (const color of row) counts.set(color, (counts.get(color) || 0) + 1)
  }
  let background = level.cells[0][0]
  let most = 0
  for (const [color, count] of counts) {
    if (count > most) {
      most = count
      background = color
    }
  }
  const subject: Paint[] = []
  const ground: Paint[] = []
  for (let z = 0; z < level.rows; z++) {
    for (let x = 0; x < level.cols; x++) {
      const color = level.cells[z][x]
      const paint = { x, z, color }
      if (color === background) ground.push(paint)
      else subject.push(paint)
    }
  }
  const ordered = subject.concat(ground)
  const count = Math.round((ordered.length * percent) / 100)
  return ordered.slice(0, count)
}

/**
 * Share of the picture that is painted the right color.
 * A wrong square counts against it.
 */
export function likeness(level: Level, paints: Paint[]): number {
  const placed = new Map<string, string>()
  for (const paint of paints) {
    if (!inCanvas(level, paint.x, paint.z)) continue
    placed.set(`${paint.x},${paint.z}`, paint.color.toLowerCase())
  }
  let figure = 0
  let hits = 0
  for (let z = 0; z < level.rows; z++) {
    for (let x = 0; x < level.cols; x++) {
      figure += 1
      const got = placed.get(`${x},${z}`)
      if (got === level.cells[z][x].toLowerCase()) hits += 1
      placed.delete(`${x},${z}`)
    }
  }
  const total = figure + placed.size
  if (total === 0) return 0
  return Math.round((hits / total) * 100)
}
